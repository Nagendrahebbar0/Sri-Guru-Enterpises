  // ============================================================
  // SECTION CARD
  // ============================================================

  Widget _sectionCard({
    required String title,
    required IconData icon,
    required List<Widget> children,
  }) {
    return Card(
      child: Padding(
        padding:
        const EdgeInsets.all(16),
        child: Column(
          crossAxisAlignment:
          CrossAxisAlignment.start,
          children: <Widget>[
            Row(
              children: <Widget>[
                Icon(icon),
                const SizedBox(width: 10),
                Text(
                  title,
                  style:
                  Theme.of(context)
                      .textTheme
                      .titleMedium
                      ?.copyWith(
                    fontWeight:
                    FontWeight.bold,
                  ),
                ),
              ],
            ),

            const SizedBox(height: 16),

            ...children,
          ],
        ),
      ),
    );
  }

  // ============================================================
  // NUMBER HELPERS
  // ============================================================

  double _roundMoney(double value) {
    return double.parse(
      value.toStringAsFixed(2),
    );
  }

  double _roundNumber(double value) {
    return double.parse(
      value.toStringAsFixed(2),
    );
  }

  String _formatNumber(double value) {
    if (value ==
        value.roundToDouble()) {
      return value.toInt().toString();
    }

    return value.toString();
  }

  // ============================================================
  // ERROR MESSAGE
  // ============================================================

  void _showError(String message) {
    ScaffoldMessenger.of(context)
        .showSnackBar(
      SnackBar(
        content: Text(message),
        behavior:
        SnackBarBehavior.floating,
      ),
    );
  }
}

// ============================================================
// CUSTOMER SEARCH DIALOG
// ============================================================
//
// Reuses the same customer-selection behavior already used
// by the Tyre Billing workflow.
//
// Search:
// - Customer Name
// - Customer Number
// ============================================================

class _CustomerSearchDialog
    extends StatefulWidget {
  const _CustomerSearchDialog();

  @override
  State<_CustomerSearchDialog> createState() =>
      _CustomerSearchDialogState();
}

class _CustomerSearchDialogState
    extends State<_CustomerSearchDialog> {
  // ------------------------------------------------------------
  // CUSTOMER REPOSITORY
  // ------------------------------------------------------------

  final CustomerRepository _repository =
  CustomerRepository();

  // ------------------------------------------------------------
  // SEARCH CONTROLLER
  // ------------------------------------------------------------

  final TextEditingController
  _searchController =
  TextEditingController();

  // ------------------------------------------------------------
  // STATE
  // ------------------------------------------------------------

  List<Customer> _customers =
  <Customer>[];

  bool _loading = true;

  // ============================================================
  // INITIALIZATION
  // ============================================================

  @override
  void initState() {
    super.initState();

    _loadCustomers();

    _searchController
        .addListener(_search);
  }

  // ============================================================
  // LOAD CUSTOMERS
  // ============================================================

  Future<void> _loadCustomers() async {
    final List<Customer> customers =
    await _repository
        .getCustomers();

    if (!mounted) {
      return;
    }

    setState(() {
      _customers = customers;
      _loading = false;
    });
  }

  // ============================================================
  // SEARCH CUSTOMERS
  // ============================================================

  Future<void> _search() async {
    final String query =
    _searchController.text.trim();

    final List<Customer> customers =
    await _repository
        .searchCustomers(query);

    if (!mounted) {
      return;
    }

    setState(() {
      _customers = customers;
    });
  }

  // ============================================================
  // DISPOSE
  // ============================================================

  @override
  void dispose() {
    _searchController
      ..removeListener(_search)
      ..dispose();

    super.dispose();
  }

  // ============================================================
  // BUILD
  // ============================================================

  @override
  Widget build(BuildContext context) {
    return AlertDialog(
      title: const Text(
        'Select Customer',
      ),

      content: SizedBox(
        width: 500,
        height: 500,
        child: Column(
          children: <Widget>[
            // --------------------------------------------------
            // SEARCH FIELD
            // --------------------------------------------------

            TextField(
              controller:
              _searchController,
              autofocus: true,
              decoration:
              const InputDecoration(
                hintText:
                'Search name or customer number',
                prefixIcon:
                Icon(Icons.search),
                border:
                OutlineInputBorder(),
              ),
            ),

            const SizedBox(height: 12),

            // --------------------------------------------------
            // CUSTOMER LIST
            // --------------------------------------------------

            Expanded(
              child: _loading
                  ? const Center(
                child:
                CircularProgressIndicator(),
              )
                  : _customers.isEmpty
                  ? const Center(
                child: Text(
                  'Customer Not Found',
                ),
              )
                  : ListView.separated(
                itemCount:
                _customers.length,
                separatorBuilder:
                    (_, _) =>
                const Divider(
                  height: 1,
                ),
                itemBuilder:
                    (
                    BuildContext context,
                    int index,
                    ) {
                  final Customer
                  customer =
                  _customers[
                  index];

                  return ListTile(
                    leading:
                    const CircleAvatar(
                      child: Icon(
                        Icons
                            .person_outline,
                      ),
                    ),
                    title: Text(
                      customer.name,
                    ),
                    subtitle: Text(
                      customer.phone,
                    ),
                    onTap: () {
                      Navigator.of(
                        context,
                      ).pop(
                        customer,
                      );
                    },
                  );
                },
              ),
            ),
          ],
        ),
      ),

      actions: <Widget>[
        TextButton(
          onPressed: () {
            Navigator.of(context)
                .pop();
          },
          child:
          const Text('Cancel'),
        ),
      ],
    );
  }
}