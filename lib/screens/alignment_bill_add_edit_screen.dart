// ============================================================
// FILE: alignment_bill_add_edit_screen.dart
//
// PURPOSE:
// Add, edit and duplicate Simple Alignment Bills.
//
// IMPORTANT:
// - Alignment Billing does NOT use GST.
// - Customer is selected from the existing Customer module.
// - Customer search supports Name OR Customer Number.
// - If a customer does not exist, Create Customer can be used.
// - First bill number is entered manually.
// - Later bill numbers are generated automatically.
// ============================================================

import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import 'package:intl/intl.dart';

import '../models/alignment_bill.dart';
import '../models/customer.dart';
import '../repositories/alignment_bill_repository.dart';
import '../repositories/customer_repository.dart';
import 'add_edit_customer_screen.dart';

class AlignmentBillAddEditScreen extends StatefulWidget {
  final AlignmentBill? bill;
  final bool isDuplicate;

  const AlignmentBillAddEditScreen({
    super.key,
    this.bill,
    this.isDuplicate = false,
  });

  @override
  State<AlignmentBillAddEditScreen> createState() =>
      _AlignmentBillAddEditScreenState();
}

class _AlignmentBillAddEditScreenState
    extends State<AlignmentBillAddEditScreen> {
  // ------------------------------------------------------------
  // FORM
  // ------------------------------------------------------------

  final GlobalKey<FormState> _formKey =
  GlobalKey<FormState>();

  // ------------------------------------------------------------
  // REPOSITORIES
  // ------------------------------------------------------------

  final AlignmentBillRepository _billRepository =
  AlignmentBillRepository();

  final CustomerRepository _customerRepository =
  CustomerRepository();

  // ------------------------------------------------------------
  // CONTROLLERS
  // ------------------------------------------------------------

  final TextEditingController _billNumberController =
  TextEditingController();

  final TextEditingController _customerNameController =
  TextEditingController();

  final TextEditingController _customerNumberController =
  TextEditingController();

  final TextEditingController _addressController =
  TextEditingController();

  final TextEditingController _vehicleNumberController =
  TextEditingController();

  final TextEditingController _kmsController =
  TextEditingController();

  final TextEditingController _serviceController =
  TextEditingController(
    text: 'Wheel Alignment',
  );

  final TextEditingController _quantityController =
  TextEditingController(
    text: '1',
  );

  final TextEditingController _rateController =
  TextEditingController();

  final TextEditingController _remarksController =
  TextEditingController();

  // ------------------------------------------------------------
  // STATE
  // ------------------------------------------------------------

  Customer? _selectedCustomer;

  DateTime _selectedDate = DateTime.now();

  String _paymentMethod = 'Cash';

  bool _loading = true;

  bool _saving = false;

  bool _isBillAutoGenerated = false;

  // ------------------------------------------------------------
  // EDIT MODE
  // ------------------------------------------------------------

  bool get _isEdit =>
      widget.bill != null &&
          !widget.isDuplicate;

  // ------------------------------------------------------------
  // BILL NUMBER LOCK
  // ------------------------------------------------------------

  bool get _isBillNumberLocked =>
      _isEdit ||
          widget.isDuplicate ||
          _isBillAutoGenerated;

  // ============================================================
  // INITIALIZATION
  // ============================================================

  @override
  void initState() {
    super.initState();

    _initialize();
  }

  Future<void> _initialize() async {
    try {
      // --------------------------------------------------------
      // EDIT
      // --------------------------------------------------------

      if (widget.bill != null) {
        await _loadExistingBill(
          widget.bill!,
        );
      } else {
        // ------------------------------------------------------
        // NEW BILL
        // ------------------------------------------------------

        final String? nextBillNumber =
        await _billRepository
            .generateNextBillNumber();

        if (nextBillNumber == null) {
          // No previous bill exists.
          //
          // The user must enter the first bill number manually.
          _billNumberController.clear();

          _isBillAutoGenerated = false;
        } else {
          // A previous bill exists, so generate the next number.
          _billNumberController.text =
              nextBillNumber;

          _isBillAutoGenerated = true;
        }
      }

      // --------------------------------------------------------
      // DUPLICATE
      // --------------------------------------------------------

      if (widget.isDuplicate &&
          widget.bill != null) {
        final String? nextBillNumber =
        await _billRepository
            .generateNextBillNumber();

        if (nextBillNumber != null) {
          _billNumberController.text =
              nextBillNumber;

          _isBillAutoGenerated = true;
        }
      }
    } catch (error) {
      if (mounted) {
        _showError(
          'Unable to load Alignment Bill.\n$error',
        );
      }
    } finally {
      if (mounted) {
        setState(() {
          _loading = false;
        });
      }
    }
  }

  // ============================================================
  // LOAD EXISTING BILL
  // ============================================================

  Future<void> _loadExistingBill(
      AlignmentBill bill,
      ) async {
    _billNumberController.text =
        bill.billNumber;

    _customerNameController.text =
        bill.customerName;

    _customerNumberController.text =
        bill.customerNumber;

    _addressController.text =
        bill.address ?? '';

    _vehicleNumberController.text =
        bill.vehicleNumber;

    _kmsController.text =
        bill.kms.toString();

    _serviceController.text =
        bill.service;

    _quantityController.text =
        _formatNumber(bill.quantity);

    _rateController.text =
        _formatNumber(bill.rate);

    _remarksController.text =
        bill.remarks;

    _selectedDate = bill.date;

    _paymentMethod =
        bill.paymentMethod;

    // Load the actual customer record when the
    // bill contains a customer ID.
    if (bill.customerId != null) {
      _selectedCustomer =
      await _customerRepository
          .getCustomerById(
        bill.customerId!,
      );
    }
  }

  // ============================================================
  // CUSTOMER SELECTION
  // ============================================================

  Future<void> _selectCustomer() async {
    final Customer? customer =
    await showDialog<Customer>(
      context: context,
      builder: (BuildContext context) {
        return const _CustomerSearchDialog();
      },
    );

    if (!mounted || customer == null) {
      return;
    }

    _applyCustomer(customer);
  }

  // ============================================================
  // APPLY CUSTOMER
  // ============================================================

  void _applyCustomer(Customer customer) {
    setState(() {
      _selectedCustomer = customer;

      _customerNameController.text =
          customer.name;

      _customerNumberController.text =
          customer.phone;

      _addressController.text =
          customer.address ?? '';
    });
  }

  // ============================================================
  // CREATE CUSTOMER
  // ============================================================

  Future<void> _createCustomer() async {
    // Keep the IDs that existed before opening the
    // Customer creation screen.
    final List<Customer> before =
    await _customerRepository
        .getCustomers();

    final Set<int> oldIds = before
        .where(
          (Customer customer) =>
      customer.id != null,
    )
        .map(
          (Customer customer) =>
      customer.id!,
    )
        .toSet();

    if (!mounted) {
      return;
    }

    final dynamic result =
    await Navigator.of(context).push(
      MaterialPageRoute<dynamic>(
        builder: (BuildContext context) {
          return const AddEditCustomerScreen();
        },
      ),
    );

    if (!mounted || result != true) {
      return;
    }

    // Read customers again after the new customer
    // was created.
    final List<Customer> after =
    await _customerRepository
        .getCustomers();

    Customer? newCustomer;

    // Find the newly-created customer.
    for (final Customer customer in after) {
      if (customer.id != null &&
          !oldIds.contains(customer.id)) {
        newCustomer = customer;
        break;
      }
    }

    // Fallback in case the database implementation
    // returns the records in an unexpected order.
    newCustomer ??=
    after.isNotEmpty
        ? after.first
        : null;

    if (newCustomer != null) {
      _applyCustomer(newCustomer);
    }
  }

  // ============================================================
  // DATE PICKER
  // ============================================================

  Future<void> _pickDate() async {
    final DateTime? picked =
    await showDatePicker(
      context: context,
      initialDate: _selectedDate,
      firstDate: DateTime(2000),
      lastDate: DateTime(2100),
    );

    if (picked == null || !mounted) {
      return;
    }

    setState(() {
      _selectedDate = DateTime(
        picked.year,
        picked.month,
        picked.day,
      );
    });
  }

  // ============================================================
  // AMOUNT CALCULATION
  // ============================================================

  double get _quantity {
    return double.tryParse(
      _quantityController.text.trim(),
    ) ??
        0;
  }

  double get _rate {
    return double.tryParse(
      _rateController.text.trim(),
    ) ??
        0;
  }

  double get _amount {
    return _quantity * _rate;
  }

  // ============================================================
  // SAVE
  // ============================================================

  Future<void> _save() async {
    // Validate all form fields first.
    if (!_formKey.currentState!.validate()) {
      return;
    }

    // A customer must be selected.
    if (_selectedCustomer == null) {
      _showError(
        'Please select a customer.',
      );
      return;
    }

    // Customer ID must exist because the selected customer
    // comes from the Customer table.
    if (_selectedCustomer!.id == null) {
      _showError(
        'Selected customer has no valid ID.',
      );
      return;
    }

    final String billNumber =
    _billNumberController.text.trim();

    // Check duplicate bill number only for new bills.
    if (!_isEdit) {
      try {
        final bool exists =
        await _billRepository
            .billNumberExists(
          billNumber,
        );

        if (exists) {
          _showError(
            'Bill number already exists.',
          );
          return;
        }
      } catch (error) {
        _showError(
          'Unable to validate bill number.\n$error',
        );
        return;
      }
    }

    setState(() {
      _saving = true;
    });

    try {
      final DateTime now =
      DateTime.now();

      final AlignmentBill alignmentBill =
      AlignmentBill(
        // Keep the existing database ID during editing.
        id: _isEdit
            ? widget.bill!.id
            : null,

        billNumber: billNumber,

        date: _selectedDate,

        customerId:
        _selectedCustomer!.id,

        customerName:
        _customerNameController
            .text
            .trim(),

        customerNumber:
        _customerNumberController
            .text
            .trim(),

        address:
        _addressController.text
            .trim()
            .isEmpty
            ? null
            : _addressController.text
            .trim(),

        vehicleNumber:
        _vehicleNumberController
            .text
            .trim(),

        kms: int.tryParse(
          _kmsController.text.trim(),
        ) ??
            0,

        service:
        _serviceController.text
            .trim(),

        quantity: _roundNumber(
          _quantity,
        ),

        rate: _roundMoney(
          _rate,
        ),

        amount: _roundMoney(
          _amount,
        ),

        paymentMethod:
        _paymentMethod,

        remarks:
        _remarksController.text
            .trim(),

        // Preserve original creation date during editing.
        createdAt: _isEdit
            ? widget.bill!.createdAt
            : now,

        updatedAt: now,
      );

      if (_isEdit) {
        // Update existing record.
        await _billRepository
            .updateBill(
          alignmentBill,
        );
      } else {
        // Insert new record.
        await _billRepository
            .addBill(
          alignmentBill,
        );
      }

      if (!mounted) {
        return;
      }

      ScaffoldMessenger.of(context)
          .showSnackBar(
        SnackBar(
          content: Text(
            _isEdit
                ? 'Alignment Bill updated successfully.'
                : 'Alignment Bill saved successfully.',
          ),
        ),
      );

      // Tell the main Alignment Billing screen
      // that the bill was saved.
      Navigator.of(context).pop(true);
    } catch (error) {
      if (mounted) {
        _showError(
          'Unable to save Alignment Bill.\n$error',
        );
      }
    } finally {
      if (mounted) {
        setState(() {
          _saving = false;
        });
      }
    }
  }

  // ============================================================
  // DISPOSE
  // ============================================================

  @override
  void dispose() {
    _billNumberController.dispose();
    _customerNameController.dispose();
    _customerNumberController.dispose();
    _addressController.dispose();
    _vehicleNumberController.dispose();
    _kmsController.dispose();
    _serviceController.dispose();
    _quantityController.dispose();
    _rateController.dispose();
    _remarksController.dispose();

    super.dispose();
  }

  // ============================================================
  // BUILD
  // ============================================================

  @override
  Widget build(BuildContext context) {
    final String title = _isEdit
        ? 'Edit Alignment Bill'
        : widget.isDuplicate
        ? 'Duplicate Alignment Bill'
        : 'New Alignment Bill';

    return Scaffold(
      appBar: AppBar(
        title: Text(title),
      ),

      body: _loading
          ? const Center(
        child:
        CircularProgressIndicator(),
      )
          : Form(
        key: _formKey,
        child: ListView(
          padding:
          const EdgeInsets.fromLTRB(
            16,
            16,
            16,
            100,
          ),
          children: <Widget>[
            _buildBillSection(),

            const SizedBox(height: 16),

            _buildCustomerSection(),

            const SizedBox(height: 16),

            _buildVehicleSection(),

            const SizedBox(height: 16),

            _buildServiceSection(),

            const SizedBox(height: 16),

            _buildPaymentSection(),

            const SizedBox(height: 16),

            _buildRemarksSection(),

            const SizedBox(height: 24),

            _buildSaveButton(),
          ],
        ),
      ),
    );
  }

  // ============================================================
  // BILL SECTION
  // ============================================================

