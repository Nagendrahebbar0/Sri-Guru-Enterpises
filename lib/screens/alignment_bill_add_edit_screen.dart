                  FilteringTextInputFormatter.allow(
                    RegExp(
                      r'^\d*\.?\d{0,2}',
                    ),
                  ),
                ],
                onChanged: (_) {
                  setState(() {});
                },
                decoration:
                const InputDecoration(
                  labelText: 'Rate',
                  prefixText: '₹ ',
                  prefixIcon: Icon(
                    Icons.currency_rupee,
                  ),
                  border:
                  OutlineInputBorder(),
                ),
                validator:
                    (String? value) {
                  final double rate =
                      double.tryParse(
                        value?.trim() ??
                            '',
                      ) ??
                          -1;

                  if (rate < 0) {
                    return 'Required';
                  }

                  return null;
                },
              ),
            ),
          ],
        ),

        const SizedBox(height: 12),

        Container(
          width: double.infinity,
          padding:
          const EdgeInsets.all(14),
          decoration:
          BoxDecoration(
            color:
            Colors.orange.shade50,
            borderRadius:
            BorderRadius.circular(
              10,
            ),
          ),
          child: Row(
            mainAxisAlignment:
            MainAxisAlignment
                .spaceBetween,
            children: <Widget>[
              const Text(
                'Total Amount',
                style: TextStyle(
                  fontWeight:
                  FontWeight.bold,
                ),
              ),
              Text(
                '₹${_amount.toStringAsFixed(2)}',
                style:
