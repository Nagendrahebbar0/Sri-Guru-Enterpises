    return _sectionCard(
      title: 'Bill Details',
      icon: Icons.receipt_long_outlined,
      children: <Widget>[
        TextFormField(
          controller:
          _billNumberController,
          readOnly: _isBillNumberLocked,
          decoration: InputDecoration(
            labelText: 'Bill Number',
            hintText:
            _isBillNumberLocked
