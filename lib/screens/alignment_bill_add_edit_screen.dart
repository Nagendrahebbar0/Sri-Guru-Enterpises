  // ============================================================
  // VEHICLE SECTION
  // ============================================================

  Widget _buildVehicleSection() {
    return _sectionCard(
      title: 'Vehicle',
      icon:
      Icons.directions_car_outlined,
      children: <Widget>[
        TextFormField(
          controller:
          _vehicleNumberController,
          textCapitalization:
          TextCapitalization.characters,
          inputFormatters:
          <TextInputFormatter>[
            FilteringTextInputFormatter.allow(
              RegExp(r'[A-Za-z0-9 -]'),
            ),
          ],
          decoration:
          const InputDecoration(
            labelText: 'Vehicle Number',
            hintText:
            'Example: KA01AB1234',
            prefixIcon: Icon(
              Icons.directions_car_outlined,
            ),
            border:
            OutlineInputBorder(),
          ),
          validator: (String? value) {
            if (value == null ||
                value.trim().isEmpty) {
              return 'Enter vehicle number';
            }

            return null;
          },
        ),

        const SizedBox(height: 12),

        TextFormField(
          controller: _kmsController,
          keyboardType:
          TextInputType.number,
          inputFormatters:
          <TextInputFormatter>[
            FilteringTextInputFormatter
                .digitsOnly,
          ],
          decoration:
          const InputDecoration(
            labelText: 'KMS',
            hintText:
            'Example: 45280',
            prefixIcon: Icon(
              Icons.speed_outlined,
            ),
            border:
            OutlineInputBorder(),
          ),
          validator: (String? value) {
            final String text =
                value?.trim() ?? '';

            if (text.isEmpty) {
              return 'Enter KMS';
            }

            final int? kms =
            int.tryParse(text);

            if (kms == null) {
              return 'Enter a valid KMS';
            }

            if (kms < 0) {
              return 'KMS cannot be negative';
            }

            return null;
          },
        ),
      ],
    );
  }

  // ============================================================
  // SERVICE SECTION
  // ============================================================

  Widget _buildServiceSection() {
    return _sectionCard(
      title: 'Alignment Service',
      icon:
      Icons.car_repair_outlined,
      children: <Widget>[
        TextFormField(
          controller:
          _serviceController,
          decoration:
          const InputDecoration(
            labelText: 'Service',
            hintText:
            'Example: Wheel Alignment',
            prefixIcon: Icon(
              Icons.car_repair_outlined,
            ),
            border:
            OutlineInputBorder(),
          ),
          validator: (String? value) {
            if (value == null ||
                value.trim().isEmpty) {
              return 'Enter service';
            }

            return null;
          },
        ),

        const SizedBox(height: 12),

        Row(
          crossAxisAlignment:
          CrossAxisAlignment.start,
          children: <Widget>[
            Expanded(
              child: TextFormField(
                controller:
                _quantityController,
                keyboardType:
                const TextInputType.numberWithOptions(
                  decimal: true,
                ),
                inputFormatters:
                <TextInputFormatter>[
                  FilteringTextInputFormatter.allow(
                    RegExp(
                      r'^\d*\.?\d{0,2}',
                    ),
                  ),
                ],
                onChanged: (_) {
                  setState(() {});
                },
                decoration:
                const InputDecoration(
                  labelText: 'Quantity',
                  prefixIcon: Icon(
                    Icons.format_list_numbered,
                  ),
                  border:
                  OutlineInputBorder(),
                ),
                validator:
                    (String? value) {
                  final double quantity =
                      double.tryParse(
                        value?.trim() ??
                            '',
                      ) ??
